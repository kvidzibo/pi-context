import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parse } from "yaml";
import { saveRequest } from "../src/capture.ts";
import { normalize } from "../src/normalize.ts";

const instructions = `# Generated agent instructions

DO NOT edit this file directly.

Sources:
- \`global-rules.md\`
- \`harness-rules/pi.md\`

After source changes, regenerate with \`scripts/render-agent-rules.sh\` and validate with \`scripts/render-agent-rules.sh --check\` from \`~/AI/settings\`.

---

# Rules

## Writing
- Fewest words that preserve meaning. No filler, repetition, or unsolicited explanation.
- Markdown: prioritize readability with clear headings, short paragraphs, and lists where useful. Consolidate duplicated information; restructure when needed. Keep essential facts and warnings.
- In responses, use absolute, URL-encoded \`file:///\` URLs for local file/directory links; never relative paths or \`~\`. Use absolute filesystem paths for image embeds.
`;

test("normalized Markdown preserves ordered blocks, list nesting and literal examples", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "pi-context-markdown-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const payload = { instructions: `<project_instructions path="/rules.md">\n${instructions}</project_instructions>` };
  const snapshot = structuredClone(payload);
  const path = await saveRequest(payload, directory, "Normalized YAML");
  const view = parse(await readFile(path, "utf8"));
  const section = view.request.instructions.sections[0];
  assert.deepEqual(section.attributes, { path: "/rules.md" });
  assert.deepEqual(section.content, [
    { heading: { level: 1, text: "Generated agent instructions" } },
    { text: "DO NOT edit this file directly." },
    { text: "Sources:" },
    { items: ["`global-rules.md`", "`harness-rules/pi.md`"] },
    { text: "After source changes, regenerate with `scripts/render-agent-rules.sh` and validate with `scripts/render-agent-rules.sh --check` from `~/AI/settings`." },
    { separator: true },
    { heading: { level: 1, text: "Rules" } },
    { heading: { level: 2, text: "Writing" } },
    { items: [
      "Fewest words that preserve meaning. No filler, repetition, or unsolicited explanation.",
      "Markdown: prioritize readability with clear headings, short paragraphs, and lists where useful. Consolidate duplicated information; restructure when needed. Keep essential facts and warnings.",
      "In responses, use absolute, URL-encoded `file:///` URLs for local file/directory links; never relative paths or `~`. Use absolute filesystem paths for image embeds.",
    ] },
  ]);
  assert.deepEqual(payload, snapshot);
  assert.deepEqual(parse(await readFile(await saveRequest(payload, directory, "YAML"), "utf8")), payload);
  assert.deepEqual(normalize('- parent\n  continuation\n  - child\n    - grandchild\n- next'), [
    { items: [
      { content: [{ text: "parent\ncontinuation" }, { items: [
        { content: [{ text: "child" }, { items: ["grandchild"] }] },
      ] }] },
      "next",
    ] },
  ]);
  assert.deepEqual(normalize('3. first\n4. next'), [{ ordered: true, start: 3, items: ["first", "next"] }]);
  assert.deepEqual(normalize('- [x] done\n- [ ] todo'), [{ items: ["[x] done", "[ ] todo"] }]);
  const literals = [
    '```md\n# Heading\n- code\n---\n```',
    '~~~md\n# Heading\n- code\n~~~',
    '    # Heading\n    - code\n    ---',
    'Example: `\n# code\n- code\n---\n`',
    'well-known; -42; `- inline`',
    '> # Quoted heading\n> - quoted item',
  ];
  for (const literal of literals) {
    assert.equal(normalize(literal), literal);
    assert.deepEqual(normalize(`# Real heading\n\n${literal}`), [
      { heading: { level: 1, text: "Real heading" } }, { text: literal },
    ]);
  }
  assert.deepEqual(normalize('# Before\n\n<cwd>/tmp</cwd>\n\n- after'), { sections: [
    { heading: { level: 1, text: "Before" } }, { tag: "cwd", content: "/tmp" }, { items: ["after"] },
  ] });
  for (const embedded of ['{"a":1}', '<tag>x</tag>']) {
    assert.deepEqual(normalize(`- parent\n  ${embedded}\n  - child\n- next`), [
      { items: [{ content: [{ text: `parent\n${embedded}` }, { items: ["child"] }] }, "next"] },
    ]);
  }
  const comment = '<!--\n{"a":1}\n<tag>x</tag>\n-->';
  assert.equal(normalize(comment), comment);
  assert.deepEqual(normalize(`# Heading\n\n${comment}`), [
    { heading: { level: 1, text: "Heading" } }, { text: comment },
  ]);
  assert.deepEqual(normalize('<wrapper>\n<!--\n</wrapper>\n-->\n</wrapper>'), {
    sections: [{ tag: "wrapper", content: '<!--\n</wrapper>\n-->\n' }],
  });
  for (const marker of ['```', '~~~', '`']) {
    const literalComment = `<!--\n${marker}\n-->\n`;
    assert.deepEqual(normalize(`<wrapper>\n${literalComment}# Heading\n</wrapper>`), {
      sections: [{ tag: "wrapper", content: [
        { text: literalComment }, { heading: { level: 1, text: "Heading" } },
      ] }],
    });
  }
  const nestedJson = JSON.stringify({ text: "# Heading\n\n- embedded" });
  assert.deepEqual(normalize(nestedJson), { text: [{ heading: { level: 1, text: "Heading" } }, { items: ["embedded"] }] });
});

test("normalized exports omit blank prose lines and whitespace-only sections, not code or source fields", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "pi-context-whitespace-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const code = '```text\nfirst\n\nlast\n```\n';
  const payload = {
    instructions: `\n\nIntro\n\n<one>\n\nAlpha\n \t\nBeta\n\n</one>\n \t\n<two>\n${code}</two>\n\n`,
    prose: '\nFirst `inline`\n\nSecond\n\n',
    multilineCode: 'Example: `\nfirst\n\nlast\n`',
    text: '',
  };
  const saved = parse(await readFile(await saveRequest(payload, directory, "Normalized YAML"), "utf8"));
  assert.deepEqual(saved.request.instructions, { sections: [
    { text: "Intro\n" }, { tag: "one", content: "Alpha\nBeta\n" }, { tag: "two", content: code },
  ] });
  assert.equal(saved.request.prose, 'First `inline`\nSecond\n');
  assert.equal(saved.request.multilineCode, payload.multilineCode);
  assert.equal(saved.request.text, '');
  assert.deepEqual(parse(await readFile(await saveRequest(payload, directory, "YAML"), "utf8")), payload);
});
